/* cardline.test.js — บรรทัดตลาดบนการ์ด ฝั่งที่ "เจ้าของมองเห็น"

   เจ้าของ: "HT/FT 17 คือไร" · "มันขาดอะไร HT/FT 17 (1/1) ไปไหน"
   และก่อนหน้านั้น: "HT/FT 17(Thu Jan 01 2026 ... เวลาอินโดจีน) เอาออกไปสักที"

   กฎที่ไฟล์นี้เฝ้า 2 ข้อ:
     1. ท่อนไหนมี 2 ส่วน (เลข + ผลที่เดา) ต้องครบทั้งคู่ ขาดข้างเดียว = ตัดทั้งท่อน
        "HT/FT 17" เดี่ยวๆ ไม่ได้บอกอะไร นอกจากทำให้อ่านผิด — "ดูผิดตายเลยนะ"
     2. ค่าที่ชีตกลืนเป็นวันที่ ห้ามหลุดออกจากเซิร์ฟเวอร์ไปโผล่บนการ์ด
*/

const { loadGas } = require('./gasEnv');
const { loadWeb } = require('./webEnv');
const { FakeSpreadsheetApp } = require('./fakeSheet');

const w = loadWeb(['web/js/fmt.js', 'web/js/page-forebet.js']);

/** ถอดแท็กออก เหลือแต่ตัวหนังสือที่ตาเจ้าของเห็นจริงๆ */
function line(p) {
  return w.marketLine_(p).replace(/<[^>]*>/g, '');
}

const FULL = {
  '1X2เปอร์เซ็นต์': '42/38/20',
  'Overเปอร์เซ็นต์': '77',
  'BTTSเปอร์เซ็นต์': '58',
  'HTเดาผล': '1', 'HTเปอร์เซ็นต์': '41/36/23',
  'DBเปอร์เซ็นต์': '80', 'DBเดาผล': '1X',
  'HTFTเปอร์เซ็นต์': '17', 'HTFTเดาผล': '1/1'
};
function but(o) {
  const p = {}, k = Object.keys(FULL);
  for (let i = 0; i < k.length; i++) p[k[i]] = FULL[k[i]];
  const m = Object.keys(o);
  for (let i = 0; i < m.length; i++) p[m[i]] = o[m[i]];
  return p;
}

test('ครบทุกช่อง = ได้บรรทัดตามที่เจ้าของเขียนมาเป๊ะ', () => {
  eq(line(FULL),
     '1X2 (42/38/20) · Over 77 · BTTS 58 · HT 1 (41/36/23) · DB 80/1X · HT/FT 17(1/1)');
});

test('ขาดผลที่เดา = ตัดทั้งท่อน ห้ามเหลือ "HT/FT 17" กับ "DB 80" ลอยๆ', () => {
  const s = line(but({ 'HTFTเดาผล': '', 'DBเดาผล': '' }));
  eq(s.indexOf('HT/FT'), -1, 'นี่คือบั๊กที่เจ้าของด่ามา — ห้ามกลับมาอีก');
  eq(s.indexOf('DB'), -1);
  eq(s, '1X2 (42/38/20) · Over 77 · BTTS 58 · HT 1 (41/36/23)', 'ท่อนอื่นต้องอยู่ครบ');
});

test('ขาดเลข เหลือแต่ผลที่เดา = ตัดทั้งท่อนเหมือนกัน', () => {
  const s = line(but({ 'HTFTเปอร์เซ็นต์': '', 'DBเปอร์เซ็นต์': '' }));
  eq(s.indexOf('HT/FT'), -1);
  eq(s.indexOf('DB'), -1);
});

test('ยังไม่ได้เปิดหน้าคู่ = โชว์เท่าที่มีจากตารางใหญ่ ไม่ใช่บรรทัดเปล่า', () => {
  eq(line({ 'เปอร์เซ็นต์': 62 }), '1X2 62%');
  eq(w.marketLine_({}), '', 'ไม่มีอะไรเลย = ไม่ต้องมีบรรทัดนี้');
  eq(w.marketLine_({ 'เปอร์เซ็นต์': 0 }), '', '0% = ยังไม่รู้ ไม่ใช่เดา 0');
});

test('HT เดี่ยวๆ ยังโชว์ได้ (อ่านรู้เรื่องทั้งคู่ ไม่ใช่ครึ่งป้าย)', () => {
  eq(line({ 'HTเดาผล': '1' }), 'HT 1');
  eq(line({ 'HTเปอร์เซ็นต์': '41/36/23' }), 'HT (41/36/23)');
});

/* ---- ต้นทาง: ห้ามให้ค่าที่ชีตกลืนเป็นวันที่ ออกจากเซิร์ฟเวอร์เลย ---- */

function apiEnv() {
  const g = loadGas(['gas/Config.gs', 'gas/Sheets.gs', 'gas/Forebet.gs', 'gas/Api.gs'], {
    SpreadsheetApp: new FakeSpreadsheetApp({}),
    Utilities: { formatDate: () => '2026-08-27T18:00:00' }
  });
  return g;
}

test('ทุกช่องตลาดที่ชีตกลืนเป็นวันที่ ต้องออกไปเป็นค่าว่าง ไม่ใช่ "เวลาอินโดจีน"', () => {
  const D = new Date(2026, 0, 1);
  const out = apiEnv().pickOut_({
    'HT/FT เดาผล': D, 'HT/FT %': D, 'DB เดาผล': D, 'DB %': D,
    'Over %': D, 'BTTS YES %': D, 'HT เดาผล': D, 'HT %': D,
    '1X2 %': D, 'เรท Over': D, 'เรท BTTS YES': D, 'HT เรท': D
  }, {});

  const k = ['HTFTเดาผล', 'HTFTเปอร์เซ็นต์', 'DBเดาผล', 'DBเปอร์เซ็นต์',
    'Overเปอร์เซ็นต์', 'BTTSเปอร์เซ็นต์', 'HTเดาผล', 'HTเปอร์เซ็นต์',
    '1X2เปอร์เซ็นต์', 'เรทOver', 'เรทBTTSYes', 'HTเรท'];
  for (let i = 0; i < k.length; i++) eq(out[k[i]], '', 'ช่อง ' + k[i] + ' ยังคาย Date ออกมา');

  eq(line(out), '', 'ปลายทางก็ต้องไม่เหลือบรรทัดตลาดให้อ่านผิด');
});
